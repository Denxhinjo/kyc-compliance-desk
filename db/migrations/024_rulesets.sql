-- ---------------------------------------------------------------------------
-- The references, added AFTER the seed so the existing rows satisfy them
-- ---------------------------------------------------------------------------
--
-- Both are nullable columns, so a NULL still means "not established" and is
-- still permitted — a foreign key constrains values that are present, which is
-- exactly the behaviour wanted here. Migration 021 deliberately leaves the
-- decision column NULL where the data could not establish a version, and that
-- must stay legal.
--
-- These make the lookup real rather than conventional: with them, a version
-- string on an application or a decision cannot name a ruleset nobody wrote
-- down. Without them, the next version bump could ship a string pointing at
-- nothing and the table would quietly stop being an answer.

alter table applications
    add constraint applications_ruleset_version_known
    foreign key (risk_ruleset_version) references rulesets (version);

alter table decisions
    add constraint decisions_ruleset_version_known
    foreign key (risk_ruleset_version_at_decision) references rulesets (version);
