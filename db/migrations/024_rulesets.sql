-- 024: what each ruleset version actually CONTAINED.
--
-- DEPLOYMENT ORDER: not file order. See the header of
-- 020_freeze_risk_after_decision.sql and docs/deploy.md. This one is
-- independent of that sequence and can be applied at any point in it.
--
-- THE GAP
--
-- Every scored application stores risk_ruleset_version, and since migration 021
-- every decision stores the version it was taken under. Both are strings. What
-- the string MEANT — which points, which thresholds, which country lists —
-- lived only in worker/scoring.py and in git history.
--
-- An auditor cannot read git. "Decided under 2026-09-1" is only an answer if
-- 2026-09-1 is something you can look up, and until now the honest reply was
-- "clone the repository and check out the right commit". This table is that
-- lookup.
--
-- WHAT IS IN A ROW, AND WHAT IS DELIBERATELY NOT
--
-- points and thresholds are what scoring.py applies. reference_data is the data
-- scoring READS — the two FATF country lists, with their source, publication
-- date, plenary and digest where the repository records one.
--
-- The sanctions list is NOT in here, and that is not an omission. Scoring never
-- reads it: screening happens first and passes its hits in. Which list version
-- informed a particular decision is already recorded per screening run, in
-- screening_results.snapshot_id -> sanctions_snapshots, because it is a property
-- of that run rather than of the rules. A decision depends on both, and the two
-- are versioned in the two places they belong.
--
-- IMMUTABLE, THE SAME WAY audit_events IS
--
-- A ruleset definition that can be edited later defends nothing. The entire
-- value of this table is that "2026-09-1 contained these points" is a statement
-- nobody can quietly revise after a decision has been defended with it — which
-- is the same argument migration 006 makes about the audit log, so it gets the
-- same mechanism rather than a second style of guard.
--
-- Corrections are made by recording a NEW version and bumping
-- scoring.RULESET_VERSION, exactly as 2026-09-2 corrected 2026-09-1's country
-- list. That is also why there is no updated_at.
--
-- WHERE THE SEEDED CONTENT CAME FROM
--
-- Not from memory, and not retyped. The rows below were generated by reading
-- worker/scoring.py for the current version and `git show ea139d3:worker/
-- scoring.py` for the previous one, so the values in this file are the values
-- the code held.
--
-- The one judgement involved was whether 2026-09-1's points could be
-- established at all, since the module has changed since. An AST comparison of
-- every upper-case module constant across the version bump (commit f15c7dc)
-- shows that only the country lists and the version string differ: every points
-- table, threshold and match band is identical. The comment above
-- RULESET_VERSION asserts the same thing, and the history corroborates it
-- rather than the other way round.
--
-- 2026-09-1's reference data carries NULL publication dates. That is an
-- ESTABLISHED absence rather than an unknown one: that version's
-- increased-monitoring list was never published by FATF — it held Monaco
-- alongside Turkiye and the UAE, a combination never issued — and the
-- repository says so itself in the provenance text recorded in the row.

create table rulesets (
    version text primary key,

    -- When this version started applying. Taken from the commit that introduced
    -- it, which is the only date the repository can actually establish.
    --
    -- Seeded decisions carry decided_at values EARLIER than this, because the
    -- seeder backdates synthetic history to make the demo look lived-in. Real
    -- decisions could not. Left as the commit date rather than stretched
    -- backwards to cover the seed, because inventing an earlier date to make
    -- the data look tidy is the failure this table exists to prevent.
    effective_from timestamptz not null,

    -- The per-signal points as scoring.py defines them.
    points jsonb not null,

    -- auto_approve_below / auto_reject_at_or_above.
    thresholds jsonb not null,

    -- The lists scoring reads, with whatever provenance the repository records
    -- for each. Nullable fields inside are meaningful: a null published_at is
    -- the data saying it does not know, or knows there is none.
    reference_data jsonb,

    -- Why this version exists. Not blank, in the database, for the same reason
    -- decisions.reason is not blank: a version with no stated reason is a row
    -- that cannot be defended by whoever has to defend it.
    change_note text not null
        constraint rulesets_change_note_not_blank
        check (length(trim(change_note)) > 0),

    recorded_at timestamptz not null default now()
);

create function rulesets_immutable() returns trigger
language plpgsql as $$
begin
    raise exception 'rulesets is append-only: % is not permitted', tg_op
        using errcode = 'restrict_violation',
              hint = 'A ruleset definition that can be edited later defends '
                     'nothing. Record a new version and bump '
                     'scoring.RULESET_VERSION instead.';
end;
$$;

-- FOR EACH STATEMENT, following migration 006 exactly: the operation is banned
-- outright, so there is nothing to inspect, it fires even on a statement
-- matching zero rows, and it costs less.
create trigger rulesets_no_update
    before update on rulesets
    for each statement execute function rulesets_immutable();

create trigger rulesets_no_delete
    before delete on rulesets
    for each statement execute function rulesets_immutable();

create trigger rulesets_no_truncate
    before truncate on rulesets
    for each statement execute function rulesets_immutable();

